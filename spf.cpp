#define max_len 10000000
int main(){
    cin.tie(nullptr); cout.tie(nullptr); ios::sync_with_stdio(false);
    vector<int>primes(max_len+1,0); // tc of the precomputation part is o(n*log(logn)) at base 2 both.
    //the nth number here is at index n+1
    //0 means non-prime
    for(int i=0;i<max_len+1;i++){
        primes[i]=i;
    }
    primes[0]=0; primes[1]=0; primes[2]=2;
    ll n=max_len;
    ll k=2; //handle 2 separatelty as the only even prime 
    //all even have 2 as SPF
    while(k*2<=n){
        primes[k*2]=2; k++;
    }

    for(ll i=3;i*i<=n;i=i+2){ // run for only odd numbers 
        //here we run fully upto root of n as for every prime number
        //its spf woulf either be itself or already marked
        if(primes[i]==i){ 
            k=i; //begin marking from i*i as lesser multiples already marked
            while((ll)(k*i)<=n){
                if(primes[k*i]==k*i){primes[k*i]=i;}
                k=k+2; //this ensures k is odd only
            }
        }
    }
        //to find prime factorization of a number using spf
    // (tc of this part is is o(log base 2 of n))
    //for ex36 gives 2. now 18 gives 2. now 9 gives 3. now 3 gives 1. 
    // stop at 1
    ll target; vector<ll>pf;
    while(target>1){
        pf.push_back(primes[target]);
        target/=primes[target];
    }
}
